alter table if exists public.student_requests
  add column if not exists reference_code text,
  add column if not exists transfer_info text not null default '',
  add column if not exists receipt text not null default '',
  add column if not exists payment_method text not null default '',
  add column if not exists payment_amount numeric not null default 0,
  add column if not exists payment_status text not null default 'pending' check (payment_status in ('pending', 'paid')),
  add column if not exists payment_date date;

create index if not exists student_requests_reference_idx on public.student_requests(reference_code);

alter table if exists public.students
  add column if not exists group_name text not null default '',
  add column if not exists previous_courses text not null default '',
  add column if not exists total_fees_paid numeric(12, 2) not null default 0,
  add column if not exists library_access_enabled boolean not null default false,
  add column if not exists library_access_password text not null default '';

alter table if exists public.student_requests
  drop constraint if exists student_requests_request_type_check;
alter table if exists public.student_requests
  add constraint student_requests_request_type_check check (request_type in ('absence', 'late', 'course_change', 'refund', 'payment', 'library_payment', 'other'));

alter table if exists public.students enable row level security;
drop policy if exists "Instructors can update assigned student records" on public.students;
create policy "Instructors can update assigned student records" on public.students
  for update to authenticated
  using (
    instructor_id = auth.uid()
    and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'instructor')
  )
  with check (instructor_id = auth.uid());

drop policy if exists "Administrators can update student records" on public.students;
create policy "Administrators can update student records" on public.students
  for update to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

