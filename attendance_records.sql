create table if not exists public.attendance_records (
  id bigint generated by default as identity primary key,
  student_profile_id uuid not null references public.profiles(id) on delete cascade,
  instructor_profile_id uuid not null references public.profiles(id) on delete restrict,
  level text not null,
  status text not null check (status in ('present', 'absent', 'late')),
  session_date date not null,
  session_time time not null,
  notes text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists attendance_records_student_idx on public.attendance_records(student_profile_id, session_date desc);
create index if not exists attendance_records_instructor_idx on public.attendance_records(instructor_profile_id, session_date desc);

