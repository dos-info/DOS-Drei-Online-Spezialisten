create table if not exists public.course_library (
  id bigint generated by default as identity primary key,
  level text not null,
  category text not null check (category in ('course', 'exercises', 'listening', 'listening_books', 'exam', 'dictionary', 'other', 'support')),
  title text not null,
  url text not null,
  library_type text not null default 'digital' check (library_type in ('paper', 'digital')),
  storage_path text,
  visible boolean not null default true,
  instructor_profile_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

